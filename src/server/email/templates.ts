import { environmentLabel } from '@/lib/env';
import { centsToRateDisplay } from '@/lib/money';
import { formatDate, formatDateTime } from '@/lib/time';

/**
 * Message templates for the SIMULATED outbox.
 *
 * These render plain text only. Nothing in this file talks to an SMTP server,
 * an email API, or any external service - the rendered body is stored in the
 * OutboxMessage table and displayed in the operator UI.
 */
export interface RenderedMessage {
  subject: string;
  bodyText: string;
}

// Read per render rather than once at module load: the label depends on
// configuration, and a constant computed at import time would be frozen to
// whatever the first process to import this file happened to be.
function signature(): string {
  return [
    '',
    '--',
    `ExpertOps (${environmentLabel().toLowerCase()})`,
    'This message was generated by a simulated outbox and was not delivered to any mail server.',
  ].join('\n');
}

function block(lines: Array<string | false | null | undefined>): string {
  return lines.filter((line): line is string => typeof line === 'string').join('\n');
}

export interface InvitationEmailInput {
  expertName: string;
  projectTitle: string;
  projectCode: string;
  clientName: string;
  message: string;
  expiresAt: Date;
  portalUrl: string;
  startDate?: Date | null;
  endDate?: Date | null;
  maxHourlyRateCents?: number | null;
  currency?: string;
}

export function renderInvitationEmail(input: InvitationEmailInput): RenderedMessage {
  return {
    subject: `Project invitation: ${input.projectTitle} (${input.projectCode})`,
    bodyText: block([
      `Hello ${input.expertName},`,
      '',
      `You have been matched to a project for ${input.clientName}.`,
      '',
      `Project: ${input.projectTitle} (${input.projectCode})`,
      input.startDate ? `Starts: ${formatDate(input.startDate)}` : null,
      input.endDate ? `Ends: ${formatDate(input.endDate)}` : null,
      typeof input.maxHourlyRateCents === 'number'
        ? `Budgeted rate ceiling: ${centsToRateDisplay(input.maxHourlyRateCents, input.currency ?? 'USD')}`
        : null,
      '',
      input.message ? `Note from the ExpertOps team:\n${input.message}` : null,
      input.message ? '' : null,
      `Please respond by ${formatDateTime(input.expiresAt)}.`,
      '',
      'Open your portal to accept or decline:',
      input.portalUrl,
      signature(),
    ]),
  };
}

