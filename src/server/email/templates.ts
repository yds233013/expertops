export interface OnboardingEmailInput {
  expertName: string;
  portalUrl: string;
  outstandingItems: string[];
}

export function renderOnboardingStartEmail(input: OnboardingEmailInput): RenderedMessage {
  return {
    subject: 'Next step: complete your ExpertOps onboarding',
    bodyText: block([
      `Hello ${input.expertName},`,
      '',
      'Thank you for accepting. Before you can be assigned to a project seat we need',
      'your onboarding checklist completed and verified by an operator.',
      '',
      'Outstanding items:',
      ...input.outstandingItems.map((item) => `  - ${item}`),
      '',
      'Complete them here:',
      input.portalUrl,
      signature(),
    ]),
  };
}

